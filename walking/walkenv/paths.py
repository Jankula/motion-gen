import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent  # the walking/ folder


def _models_dir():
    """A folder containing smplx/SMPLX_NEUTRAL.npz: $WALKENV_MODELS, walking/models, or the unzipped download."""
    if "WALKENV_MODELS" in os.environ:
        return Path(os.environ["WALKENV_MODELS"])
    candidates = [ROOT / "models", ROOT.parent / "models_smplx_v1_1" / "models"]
    return next((d for d in candidates if (d / "smplx").is_dir()), candidates[0])


MODELS_DIR = _models_dir()
KIT_DIR = ROOT / "agent_kit"  # files copied into every agent workspace
BODY_INFO = KIT_DIR / "body_info.json"  # generated by `python -m walkenv.body_info`
RUNS_DIR = ROOT / "runs"

_venv = ROOT / ".venv" / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
PYTHON = _venv if _venv.exists() else Path(sys.executable)  # the interpreter agents are told to use
